"""WP57e: re-letter the appendices by the order of first mention (one pass, from the base commit).

The map is computed, not typed: the letters from ``map_counts.py``'s first-mention order on the
paper at the base commit, the subsection numbers consecutive from 1 in their current order, and the
cell ids from the supporting notebook's own structure at the base (a numbered id takes the new
number of the subsection it sits in; a worded id keeps its word under the new letter).

    uv run python work-packages/WP57-rounds/e/reletter.py --dry-run FILE ...
    uv run python work-packages/WP57-rounds/e/reletter.py FILE ...
    uv run python work-packages/WP57-rounds/e/reletter.py --map     # print the maps

Every token is replaced in a single regular-expression pass per text, so no replacement is read
again (D to B and B to E never chain). Modes by file: a notebook has its sources and cell ids
rewritten (outputs are regenerated by ``paper/execute_notebooks.py``); ``claims_register.toml``
only its ``anchor`` and ``fragment`` fields; ``paper/length_ledger.toml`` only its section keys
(the ``[baseline.sections]`` block and each row's ``section`` field, the row's text as written);
``scripts/residuals_baseline.json`` only its surface keys; any other file in full. Tokens that name
a subsection the base does not have (a cut one, in a dated phrase) are left and reported.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BASE = "6d86038d"
ORDER = "GDHABCEF"  # first mention on the paper at the base (map_counts.py)
LETTER = {old: "ABCDEFGH"[i] for i, old in enumerate(ORDER)}


def _base_notebook() -> dict:
    out = subprocess.run(
        ["git", "-C", str(ROOT), "show", f"{BASE}:paper/supporting_material.ipynb"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return json.loads(out)


def structure() -> tuple[dict[tuple[str, int], int], dict[str, str]]:
    """The subsection map ((old letter, old n) -> new n) and the cell-id map (old -> new)."""
    nb = _base_notebook()
    subs: dict[str, list[int]] = {}
    where = []  # (cell id, letter or None, old subsection number or None)
    letter = n = None
    for c in nb["cells"]:
        src = "".join(c["source"])
        m = re.search(r"^## Appendix ([A-H])\.", src, re.M)
        if m:
            letter, n = m.group(1), None
            subs.setdefault(letter, [])
        m = re.search(r"^### ([A-H])\.(\d+) ", src, re.M)
        if m:
            letter, n = m.group(1), int(m.group(2))
            subs[letter].append(n)
        where.append((c.get("id"), letter, n))
    submap = {(L, old): i for L, ns in subs.items() for i, old in enumerate(ns, 1)}
    ids = {}
    for cid, L, n in where:
        m = re.fullmatch(r"(app|tab|sent)-([A-H])(-.*)?", cid or "")
        if not m:
            continue
        kind, old, rest = m.group(1), m.group(2), m.group(3) or ""
        num = re.match(r"-(\d+)(.*)", rest)
        if kind == "app" and num:
            assert old == L and n is not None, cid
            rest = f"-{submap[(L, n)]}{num.group(2)}"
        ids[cid] = f"{kind}-{LETTER[old]}{rest}"
    return submap, ids


SUBMAP, IDS = structure()
FLAGS: list[str] = []


def _sub(letter: str, n: str, where: str, token: str) -> str | None:
    key = (letter.upper(), int(n))
    if key not in SUBMAP:
        FLAGS.append(f"{where}: {token!r} names no subsection of the base; left")
        return None
    return str(SUBMAP[key])


def _case(new: str, like: str) -> str:
    return new.lower() if like.islower() else new


TOKEN = re.compile(
    r"(?P<id>\b(?:app|tab|sent)-[A-H](?:-[A-Za-z0-9_]+)*)"
    r"|(?P<lab>\b(?:tab|sent)-[a-h]-)"
    r"|(?P<anc>\bappendix-[a-h]\b)"
    r"|(?P<sub>\bsub-[a-h]-\d+\b)"
    r"|(?P<app>\bAppendix [A-H](?:\.\d+)?\b)"
    r"|(?P<apps>\bAppendices [A-H](?:(?:, | and | or | to )[A-H]\b)+)"
    r"|(?P<const>(?<![\w.])_[A-H]\d*\b)"
    r"|(?P<bare>(?<![\w.\-/])[A-H]\.\d+\b(?!\.\d))"
)


def rewrite(text: str, where: str, consts: bool = False) -> str:
    def repl(m: re.Match) -> str:
        t = m.group(0)
        kind = m.lastgroup
        if kind == "id":
            parts = t.split("-")
            for k in range(len(parts), 1, -1):  # the longest known id it starts with
                head = "-".join(parts[:k])
                if head in IDS:
                    return IDS[head] + t[len(head) :]
            FLAGS.append(f"{where}: id {t!r} not in the base notebook; letter only")
            return f"{parts[0]}-{LETTER[parts[1]]}" + t[len(parts[0]) + 2 :]
        if kind == "lab":
            p, L = t.split("-")[:2]
            return f"{p}-{LETTER[L.upper()].lower()}-"
        if kind == "anc":
            return "appendix-" + LETTER[t[-1].upper()].lower()
        if kind == "sub":
            _, L, n = t.split("-")
            new = _sub(L, n, where, t)
            return t if new is None else f"sub-{LETTER[L.upper()].lower()}-{new}"
        if kind == "app":
            L = t[9]
            if "." in t:
                new = _sub(L, t[11:], where, t)
                return t if new is None else f"Appendix {LETTER[L]}.{new}"
            return f"Appendix {LETTER[L]}"
        if kind == "apps":
            FLAGS.append(f"{where}: {t!r} a list or range of letters; for a reader")
            return t
        if kind == "const":
            if not consts:
                return t
            L, n = t[1], t[2:]
            if not n:
                return f"_{LETTER[L]}"
            new = _sub(L, n, where, t)
            return t if new is None else f"_{LETTER[L]}{new}"
        if kind == "bare":
            L, n = t.split(".")
            new = _sub(L, n, where, t)
            return t if new is None else f"{LETTER[L]}.{new}"
        raise AssertionError(kind)

    return TOKEN.sub(repl, text)


def do_notebook(path: Path) -> str:
    import nbformat

    nb = nbformat.read(path, as_version=4)
    for i, c in enumerate(nb.cells):
        if c.get("id") in IDS:
            c["id"] = IDS[c["id"]]
        c.source = rewrite(c.source, f"{path.name} cell {i}")
    if path.name == "supporting_material.ipynb":
        nb.cells = _reorder(nb.cells)
    return nbformat.writes(nb) + "\n"


def _reorder(cells: list) -> list:
    """The appendices in letter order, each appendix's cells a block in their own order."""
    blocks: dict[str, list] = {"": []}
    current = ""
    for c in cells:
        m = re.search(r"^## Appendix ([A-H])\.", c.source, re.M)
        if m:
            current = m.group(1)
            blocks[current] = []
        blocks[current].append(c)
    return blocks[""] + [c for L in "ABCDEFGH" for c in blocks[L]]


def do_register(path: Path) -> str:
    out = []
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(keepends=True), 1):
        if line.startswith(("anchor = ", "fragment = ")):
            line = rewrite(line, f"{path.name}:{i}")
        out.append(line)
    return "".join(out)


def do_ledger(path: Path) -> str:
    out, in_base = [], False
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(keepends=True), 1):
        if line.startswith("["):
            in_base = line.strip() == "[baseline.sections]"
        key = re.match(r'"Appendix [A-H]" = ', line) or line.startswith('section = "Appendix ')
        if (in_base and (key or line.startswith("#"))) or (not in_base and key):
            line = rewrite(line, f"{path.name}:{i}")
        out.append(line)
    return "".join(out)


def _surface_key(k: str) -> str:
    """A surface key in the new letters; a key naming a subsection the base lacks is a stale
    entry: it keeps its name (it counts only in the file's totals) unless the name is taken."""
    m = re.fullmatch(r"appendix/([a-h])-(\d+)", k)
    if m:
        L, n = m.group(1).upper(), int(m.group(2))
        if (L, n) in SUBMAP:
            return f"appendix/{LETTER[L].lower()}-{SUBMAP[(L, n)]}"
        return k
    if k.startswith("appendix/appendix-h-horopca"):  # the old H's slug: H was not matched as a code
        return "appendix/appendix-c"
    if re.fullmatch(r"appendix/appendix-[a-h]", k):
        return "appendix/appendix-" + LETTER[k[-1].upper()].lower()
    return k


def do_residuals(path: Path) -> str:
    """Rename the appendix surfaces; keep every entry, so each file's totals are unchanged.

    Two readings of the checker (``prose_surfaces``): a stale entry whose name the new letters
    take (the old ``g-2``, the reading pass, against the new G.2) moves to its letter under the map
    (``a-2``, which A does not have); and the front matter (two words), folded into the next piece
    of the same status, now folds into Appendix A, so A's counts are read under
    ``appendix/title`` and the old front-matter entry keeps its counts under
    ``appendix/appendix-a``, a key the report no longer produces (counted in the totals only).
    """
    data = json.loads(path.read_text(encoding="utf-8"))
    live = {f"appendix/{LETTER[L].lower()}-{n}" for (L, _), n in SUBMAP.items()}  # new names
    surfaces = {}
    for k, v in data["surfaces"].items():
        new = _surface_key(k)
        if new == k and k in live:
            m = re.fullmatch(r"appendix/([a-h])-(\d+)", k)
            new = f"appendix/{LETTER[m.group(1).upper()].lower()}-{m.group(2)}"
            FLAGS.append(f"{path.name}: stale {k!r} moved to {new!r}")
        assert new not in surfaces, new
        surfaces[new] = v
    surfaces["appendix/title"], surfaces["appendix/appendix-a"] = (
        surfaces["appendix/appendix-a"],
        surfaces["appendix/title"],
    )
    data["surfaces"] = surfaces
    text = json.dumps(data, indent=1) + "\n"
    return re.sub(
        r'"first_surface": "(appendix/[^"]+)"',
        lambda m: f'"first_surface": "{_surface_key(m.group(1))}"',
        text,
    )


def run(path: Path) -> str:
    rel = path.resolve().relative_to(ROOT).as_posix()
    if path.suffix == ".ipynb":
        return do_notebook(path)
    if rel == "claims_register.toml":
        return do_register(path)
    if rel == "paper/length_ledger.toml":
        return do_ledger(path)
    if rel == "scripts/residuals_baseline.json":
        return do_residuals(path)
    text = path.read_text(encoding="utf-8")
    return rewrite(text, rel, consts=rel == "paper/generate_findings.py")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--map", action="store_true")
    args = ap.parse_args(argv)
    if args.map:
        print("letters:", ", ".join(f"{o} -> {n}" for o, n in LETTER.items()))
        for (L, o), n in sorted(SUBMAP.items()):
            print(f"  {L}.{o} -> {LETTER[L]}.{n}")
        for o, n in IDS.items():
            print(f"  {o} -> {n}")
    for p in args.files:
        before = p.read_text(encoding="utf-8")
        after = run(p)
        if args.dry_run:
            import difflib

            for ln in difflib.unified_diff(
                before.splitlines(), after.splitlines(), str(p), str(p), n=0, lineterm=""
            ):
                if ln.startswith(("+", "-")) and not ln.startswith(("+++", "---")):
                    print(ln[:240])
        elif after != before:
            p.write_text(after, encoding="utf-8")
    for f in FLAGS:
        print("FLAG", f, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
